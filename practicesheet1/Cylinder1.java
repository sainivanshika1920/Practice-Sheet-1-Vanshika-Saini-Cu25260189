public class Cylinder1{
    public static void main(String[] args){
        double radius=5.0;
        double height=10.0;
        double volume = Math.PI * radius * radius * height;
        System.out.println("Radius = " + radius); 
        System.out.println("Height = " + height); 
        System.out.println("Volume = " + volume); 
    }
}